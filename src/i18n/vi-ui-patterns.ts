/** Returns undefined for unrecognized dynamic UI strings; no broad heuristic replacements. */
export function localizeVietnameseDynamicUi(input: string): string | undefined {
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(input)) return input.replace(pattern, replacement)
  }
  return undefined
}
